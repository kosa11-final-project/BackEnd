CREATE TABLE strategy_execution_result (
    strategy_execution_result_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    final_selection_id            NUMBER        NOT NULL,
    result_status                 VARCHAR2(20)  DEFAULT 'RUNNING' NOT NULL,
    planned_start_date            DATE          NOT NULL,
    planned_end_date              DATE          NOT NULL,
    goal_metric_code              VARCHAR2(50)  DEFAULT 'SALES_QTY' NOT NULL,
    goal_target_value             NUMBER(18,4),
    goal_actual_value             NUMBER(18,4),
    achievement_rate              NUMBER(10,6),
    start_risk_stock_qty          NUMBER(15,3),
    end_risk_stock_qty            NUMBER(15,3),
    start_expected_disposal_qty   NUMBER(15,3),
    end_expected_disposal_qty     NUMBER(15,3),
    start_unit_cost               NUMBER(18,2),
    estimated_loss_savings_amount NUMBER(18,2),
    finalized_sync_run_id         NUMBER,
    calculation_version           VARCHAR2(50)  DEFAULT 'SALES_ONLY_V1' NOT NULL,
    failure_reason                VARCHAR2(1000),
    start_captured_at             TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at                  TIMESTAMP,
    created_at                    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at                    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    created_by                    NUMBER        NOT NULL,
    updated_by                    NUMBER        NOT NULL,
    is_deleted                    NUMBER(1)     DEFAULT 0 NOT NULL,

    CONSTRAINT pk_strategy_execution_result PRIMARY KEY (strategy_execution_result_id),
    CONSTRAINT uq_strategy_execution_result_selection UNIQUE (final_selection_id),
    CONSTRAINT fk_strategy_execution_result_selection FOREIGN KEY (final_selection_id)
        REFERENCES final_strategy_selection (final_selection_id),
    CONSTRAINT fk_strategy_execution_result_sync FOREIGN KEY (finalized_sync_run_id)
        REFERENCES inventory_sync_run (inventory_sync_run_id),
    CONSTRAINT fk_strategy_execution_result_created_by FOREIGN KEY (created_by)
        REFERENCES app_user (user_id),
    CONSTRAINT fk_strategy_execution_result_updated_by FOREIGN KEY (updated_by)
        REFERENCES app_user (user_id),
    CONSTRAINT ck_strategy_execution_result_status
        CHECK (result_status IN ('RUNNING', 'PARTIAL', 'COMPLETED')),
    CONSTRAINT ck_strategy_execution_result_period
        CHECK (planned_end_date >= planned_start_date),
    CONSTRAINT ck_strategy_execution_result_target
        CHECK (goal_target_value IS NULL OR goal_target_value > 0),
    CONSTRAINT ck_strategy_execution_result_achievement
        CHECK (achievement_rate IS NULL OR achievement_rate >= 0),
    CONSTRAINT ck_strategy_execution_result_quantities CHECK (
        (start_risk_stock_qty IS NULL OR start_risk_stock_qty >= 0)
        AND (end_risk_stock_qty IS NULL OR end_risk_stock_qty >= 0)
        AND (start_expected_disposal_qty IS NULL OR start_expected_disposal_qty >= 0)
        AND (end_expected_disposal_qty IS NULL OR end_expected_disposal_qty >= 0)
        AND (start_unit_cost IS NULL OR start_unit_cost >= 0)
    ),
    CONSTRAINT ck_strategy_execution_result_completed CHECK (
        result_status <> 'COMPLETED'
        OR (
            goal_target_value IS NOT NULL
            AND goal_actual_value IS NOT NULL
            AND achievement_rate IS NOT NULL
            AND start_risk_stock_qty IS NOT NULL
            AND end_risk_stock_qty IS NOT NULL
            AND start_expected_disposal_qty IS NOT NULL
            AND end_expected_disposal_qty IS NOT NULL
            AND estimated_loss_savings_amount IS NOT NULL
            AND finalized_sync_run_id IS NOT NULL
            AND completed_at IS NOT NULL
        )
    ),
    CONSTRAINT ck_strategy_execution_result_deleted CHECK (is_deleted IN (0, 1))
);

ALTER TABLE strategy_action
    ADD CONSTRAINT ck_strategy_action_execution_dates CHECK (
        start_date IS NULL OR end_date IS NULL OR end_date >= start_date
    );

CREATE INDEX ix_strategy_action_option_dates
    ON strategy_action (strategy_option_id, end_date, start_date, is_deleted);

CREATE INDEX ix_strategy_execution_result_due
    ON strategy_execution_result (result_status, planned_end_date, is_deleted);

COMMENT ON TABLE strategy_execution_result
    IS '최종 선택된 AI 전략의 시작 기준값과 종료 후 확정 성과를 저장하는 통계 원장';
COMMENT ON COLUMN strategy_execution_result.result_status
    IS 'RUNNING 실행 중, PARTIAL 필수값 부족, COMPLETED 최종 통계 집계 가능';
COMMENT ON COLUMN strategy_execution_result.planned_start_date
    IS '선택 옵션의 활성 strategy_action.start_date 최솟값';
COMMENT ON COLUMN strategy_execution_result.planned_end_date
    IS '선택 옵션의 활성 strategy_action.end_date 최댓값';
COMMENT ON COLUMN strategy_execution_result.goal_metric_code
    IS '목표 달성률 기준. SALES_QTY는 실제 판매량만 인정하며 재고 이동량은 제외';
COMMENT ON COLUMN strategy_execution_result.goal_target_value
    IS '선택 옵션의 확정 simulation.expected_sales_qty';
COMMENT ON COLUMN strategy_execution_result.goal_actual_value
    IS '계획 시작일부터 종료일까지 집계한 실제 판매량. 이동만 된 재고는 제외';
COMMENT ON COLUMN strategy_execution_result.achievement_rate
    IS 'goal_actual_value / goal_target_value * 100';
COMMENT ON COLUMN strategy_execution_result.start_risk_stock_qty
    IS '전략 시작 기준 대상 재고의 위험수량';
COMMENT ON COLUMN strategy_execution_result.end_risk_stock_qty
    IS '종료 후 동기화와 위험등급 재산정이 끝난 대상 범위의 위험수량';
COMMENT ON COLUMN strategy_execution_result.estimated_loss_savings_amount
    IS '(시작 예상폐기수량 - 종료 예상폐기수량) * 시작 기준 원가. 악화 시 음수';
COMMENT ON COLUMN strategy_execution_result.finalized_sync_run_id
    IS '종료 성과 계산에 사용한 성공 inventory_sync_run';
COMMENT ON COLUMN strategy_execution_result.calculation_version
    IS '성과 산식 버전. SALES_ONLY_V1은 재고 이동량을 목표 달성에서 제외';
