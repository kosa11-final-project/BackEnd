CREATE TABLE strategy_execution_result (
    strategy_execution_result_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    final_selection_id            NUMBER        NOT NULL,
    goal_metric_code              VARCHAR2(50)  NOT NULL,
    goal_target_value             NUMBER(18,4)  NOT NULL,
    goal_actual_value             NUMBER(18,4)  NOT NULL,
    achievement_rate              NUMBER(10,6)  NOT NULL,
    start_risk_stock_qty          NUMBER(15,3)  NOT NULL,
    end_risk_stock_qty            NUMBER(15,3)  NOT NULL,
    start_expected_disposal_qty   NUMBER(15,3)  NOT NULL,
    end_expected_disposal_qty     NUMBER(15,3)  NOT NULL,
    estimated_loss_savings_amount NUMBER(18,2)  NOT NULL,
    calculation_version           VARCHAR2(50)  NOT NULL,
    created_at                    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at                    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    created_by                    NUMBER        NOT NULL,
    updated_by                    NUMBER        NOT NULL,
    is_deleted                    NUMBER(1)     DEFAULT 0 NOT NULL,

    CONSTRAINT pk_strategy_execution_result
        PRIMARY KEY (strategy_execution_result_id),
    CONSTRAINT uq_strategy_execution_result_selection
        UNIQUE (final_selection_id),
    CONSTRAINT fk_strategy_execution_result_selection
        FOREIGN KEY (final_selection_id)
            REFERENCES final_strategy_selection (final_selection_id),
    CONSTRAINT fk_strategy_execution_result_created_by
        FOREIGN KEY (created_by)
            REFERENCES app_user (user_id),
    CONSTRAINT fk_strategy_execution_result_updated_by
        FOREIGN KEY (updated_by)
            REFERENCES app_user (user_id),
    CONSTRAINT ck_strategy_execution_result_target
        CHECK (goal_target_value > 0),
    CONSTRAINT ck_strategy_execution_result_achievement
        CHECK (achievement_rate >= 0),
    CONSTRAINT ck_strategy_execution_result_quantities
        CHECK (
            start_risk_stock_qty >= 0
            AND end_risk_stock_qty >= 0
            AND start_expected_disposal_qty >= 0
            AND end_expected_disposal_qty >= 0
        ),
    CONSTRAINT ck_strategy_execution_result_deleted
        CHECK (is_deleted IN (0, 1))
);

ALTER TABLE strategy_action
    ADD CONSTRAINT ck_strategy_action_execution_dates
        CHECK (
            start_date IS NULL
            OR end_date IS NULL
            OR end_date >= start_date
        );

CREATE INDEX ix_strategy_action_option_dates
    ON strategy_action (strategy_option_id, end_date, start_date, is_deleted);

CREATE INDEX ix_strategy_execution_result_active
    ON strategy_execution_result (is_deleted, final_selection_id);

COMMENT ON TABLE strategy_execution_result
    IS '최종 선택된 AI 전략 실행이 종료될 때 확정한 통계용 성과 결과';
COMMENT ON COLUMN strategy_execution_result.final_selection_id
    IS '실제로 실행된 final_strategy_selection 식별자. 선택 전략당 결과는 한 건';
COMMENT ON COLUMN strategy_execution_result.goal_metric_code
    IS '목표 달성률의 기준 지표 코드';
COMMENT ON COLUMN strategy_execution_result.goal_target_value
    IS '전략 실행 전 확정한 목표값';
COMMENT ON COLUMN strategy_execution_result.goal_actual_value
    IS '전략 실행 종료 시 측정한 실제값';
COMMENT ON COLUMN strategy_execution_result.achievement_rate
    IS 'goal_actual_value / goal_target_value * 100으로 계산한 목표 달성률';
COMMENT ON COLUMN strategy_execution_result.start_risk_stock_qty
    IS '전략 실행 시작 시점의 위험재고 수량';
COMMENT ON COLUMN strategy_execution_result.end_risk_stock_qty
    IS '전략 실행 종료 시점의 위험재고 수량';
COMMENT ON COLUMN strategy_execution_result.start_expected_disposal_qty
    IS '전략 실행 시작 시점의 예상 폐기수량';
COMMENT ON COLUMN strategy_execution_result.end_expected_disposal_qty
    IS '전략 실행 종료 시점의 예상 폐기수량';
COMMENT ON COLUMN strategy_execution_result.estimated_loss_savings_amount
    IS '전략 실행으로 줄어든 것으로 평가한 추정 손실 금액. 악화 시 음수 가능';
COMMENT ON COLUMN strategy_execution_result.calculation_version
    IS '성과 산식 및 위험평가 규칙 버전';
