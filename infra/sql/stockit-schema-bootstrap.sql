    INSERT (
        role_code,
        role_name,
        created_at,
        updated_at,
        created_by,
        updated_by,
        is_deleted
    )
    VALUES (
        source.role_code,
        source.role_name,
        SYSTIMESTAMP,
        SYSTIMESTAMP,
        source.system_user_id,
        source.system_user_id,
        0
    );


